/** Returns the districts available for a given state. Only Tamil Nadu is populated. */
export function getDistricts(state: string): string[] {
  if (state === "Tamil Nadu") return TAMIL_NADU_DISTRICTS;
  return [];
}

/** Returns the taluks for a given district (empty if the district is unknown). */
export function getTaluks(district: string): string[] {
  if (!district) return [];
  return TAMIL_NADU_TALUKS[district] ?? [];
}
